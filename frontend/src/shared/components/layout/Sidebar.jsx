import { useAuth } from '../../context/AuthContext.jsx'

function SidebarLink({ to, icon, children }) {
  const location = useLocation()
  const isActive = location.pathname.startsWith(to)

  return (
    <Link
      to={to}
      className={`flex items-center px-4 py-2 text-sm font-medium rounded-md transition-colors ${isActive ? 'bg-blue-50 text-blue-600' : 'text-gray-600 hover:bg-gray-50 hover:text-gray-900'}`}
    >
      {icon && (
        <span className="mr-3">{icon}</span>
      )}
      {children}
    </Link>
  )
}

